import os
import re
from pathlib import Path
import numpy as np

CALIB_FOLDER = "calibration2"

# ── Module-level polynomial fit ─────────────────────────────────
# Populated by load_all_calibrations() when poly_fit.npz is found.
# get_homography() uses it automatically; falls back to piecewise if None.
_poly_coeffs = None   # np.ndarray shape (3, 3, degree+1), or None
_poly_degree = 2


# ── Filename helpers ────────────────────────────────────────────

def filename_to_z_mm(filename: str) -> int:
    """
    Convert filename like z_0.npz / z_10.npz into integer Z in mm.
    """
    stem = os.path.splitext(filename)[0]
    match = re.fullmatch(r"z_(-?\d+)", stem)
    if not match:
        raise ValueError(f"Invalid calibration filename format: {filename}")
    return int(match.group(1))


def normalize_homography(H: np.ndarray) -> np.ndarray:
    """Normalize so H[2,2] == 1 before interpolation/comparison."""
    H = H.astype(np.float64)
    if H.shape != (3, 3):
        raise ValueError(f"Homography must be 3x3, got {H.shape}")
    if abs(H[2, 2]) < 1e-12:
        raise ValueError("Cannot normalize: H[2,2] is too close to zero.")
    return H / H[2, 2]


# ── Polynomial best-fit ─────────────────────────────────────────

def H_from_poly(z: float) -> np.ndarray:
    """
    Evaluate the polynomial fit at height z and return a normalised 3x3 H.
    Requires load_all_calibrations() to have been called first with a folder
    that contains poly_fit.npz (generated by calibration_bestfit.py --save).
    """
    if _poly_coeffs is None:
        raise RuntimeError(
            "No polynomial fit loaded. "
            "Run:  python scripts/calibration_bestfit.py --save"
        )
    H = np.zeros((3, 3))
    for i in range(3):
        for j in range(3):
            H[i, j] = np.polyval(_poly_coeffs[i, j], z)
    if abs(H[2, 2]) > 1e-12:
        H /= H[2, 2]
    return H


# ── Load calibrations ───────────────────────────────────────────

def load_all_calibrations(folder: str = CALIB_FOLDER) -> dict:
    """
    Load all z_*.npz calibration matrices from folder.

    Also tries to load poly_fit.npz from the same folder.
    If found, get_homography() will automatically use the polynomial fit
    instead of piecewise linear interpolation — no other code changes needed.

    Returns:
        { z_mm (int): H (3x3 np.ndarray), ... }
    """
    global _poly_coeffs, _poly_degree

    calibrations = {}

    if not os.path.exists(folder):
        raise FileNotFoundError(f"Calibration folder not found: {folder}")

    for file in os.listdir(folder):
        if not file.endswith(".npz"):
            continue
        if file == "poly_fit.npz":
            continue   # loaded separately below

        path = os.path.join(folder, file)
        try:
            z_mm = filename_to_z_mm(file)
            data = np.load(path)

            if "H" not in data:
                print(f"[WARNING] {file} has no 'H' key. Skipped.")
                continue

            H = data["H"]
            if H.shape != (3, 3):
                print(f"[WARNING] {file} has invalid H shape: {H.shape}. Skipped.")
                continue

            calibrations[z_mm] = normalize_homography(H)

        except Exception as e:
            print(f"[WARNING] Could not load {file}: {e}")

    if not calibrations:
        raise ValueError("No valid calibration files were loaded.")

    # ── Load polynomial fit if available ────────────────────────
    poly_path = Path(folder) / "poly_fit.npz"
    if poly_path.exists():
        try:
            pdata        = np.load(str(poly_path))
            _poly_coeffs = pdata["coeffs"]      # shape (3, 3, degree+1)
            _poly_degree = int(pdata["degree"])
            print(f"[INFO] Polynomial fit loaded (degree {_poly_degree}) "
                  f"from {poly_path.name}  [{len(calibrations)} calibration points]")
        except Exception as e:
            _poly_coeffs = None
            print(f"[WARNING] Could not load poly_fit.npz: {e} "
                  f"— falling back to piecewise linear.")
    else:
        _poly_coeffs = None
        print(f"[INFO] No poly_fit.npz in '{folder}' "
              f"— using piecewise linear interpolation.")

    return dict(sorted(calibrations.items()))


def get_available_z(calibrations: dict) -> list:
    return sorted(calibrations.keys())


# ── Piecewise linear (fallback) ─────────────────────────────────

def interpolate_matrices(H1: np.ndarray, H2: np.ndarray, t: float) -> np.ndarray:
    """
    Linear interpolation/extrapolation between two homography matrices.
    t=0 → H1,  t=1 → H2,  t outside [0,1] → extrapolation.
    """
    H = (1.0 - t) * H1 + t * H2
    return normalize_homography(H)


def _get_homography_piecewise(z_mm: float, calibrations: dict) -> np.ndarray:
    available_z = get_available_z(calibrations)

    if len(available_z) < 2:
        raise ValueError("At least two calibration matrices are needed.")

    if z_mm in calibrations:
        return calibrations[z_mm]

    if z_mm < available_z[0]:
        z1, z2 = available_z[0], available_z[1]
        t = (z_mm - z1) / (z2 - z1)
        return interpolate_matrices(calibrations[z1], calibrations[z2], t)

    if z_mm > available_z[-1]:
        z1, z2 = available_z[-2], available_z[-1]
        t = (z_mm - z1) / (z2 - z1)
        return interpolate_matrices(calibrations[z1], calibrations[z2], t)

    for i in range(len(available_z) - 1):
        z1, z2 = available_z[i], available_z[i + 1]
        if z1 <= z_mm <= z2:
            t = (z_mm - z1) / (z2 - z1)
            return interpolate_matrices(calibrations[z1], calibrations[z2], t)

    raise ValueError(f"Could not compute homography for z={z_mm}")


# ── Main homography getter ──────────────────────────────────────

def get_homography(z_mm: float, calibrations: dict) -> np.ndarray:
    """
    Return a homography for any requested Z height.

    Uses polynomial best-fit if poly_fit.npz was loaded by
    load_all_calibrations().  Otherwise falls back to piecewise linear
    interpolation/extrapolation between the nearest measured calibrations.
    """
    if _poly_coeffs is not None:
        return H_from_poly(z_mm)
    return _get_homography_piecewise(z_mm, calibrations)


# ── Coordinate conversion ───────────────────────────────────────

def pixel_to_world(pixel_xy, H):
    """Convert image pixel to world coordinates in mm using homography H."""
    px, py = pixel_xy
    p_img = np.array([px, py, 1.0], dtype=np.float64)
    p_world = H @ p_img

    if abs(p_world[2]) < 1e-12:
        raise ZeroDivisionError("Homogeneous coordinate too close to zero.")

    p_world /= p_world[2]
    return float(p_world[0]), float(p_world[1])


def pixel_to_world_at_height(pixel_xy, z_mm: float, calibrations: dict):
    """
    Convenience: pixel + Z height → world mm.
    Uses polynomial fit if available, otherwise piecewise linear.
    """
    H = get_homography(z_mm, calibrations)
    return pixel_to_world(pixel_xy, H)


if __name__ == "__main__":
    calibrations = load_all_calibrations()

    print("Loaded Z values:", get_available_z(calibrations))
    print("Using polynomial fit:", _poly_coeffs is not None)

    test_heights = [0, 10, 25, 45, 60]

    for z in test_heights:
        H = get_homography(z, calibrations)
        print(f"\nZ = {z} mm")
        print(H)
        x_mm, y_mm = pixel_to_world((640, 360), H)
        print(f"Pixel (640, 360) -> ({x_mm:.2f}, {y_mm:.2f}) mm")
